#!/usr/bin/env python3
"""
BioSecure AI — Dynamic Nginx Configuration & Load Balancer Setup.

Generates self-contained, portable Nginx configurations for both Linux and Windows.
Supports single-node reverse proxying and multi-server horizontal load balancing.
"""

from __future__ import annotations

import argparse
import os
import platform
import socket
import sys
from pathlib import Path

# Project root directory (one level up from nginx/)
PROJECT_ROOT = Path(__file__).resolve().parent.parent
NGINX_DIR = PROJECT_ROOT / "nginx"


def is_port_free(port: int, host: str = "0.0.0.0") -> bool:
    """Return True if the specified port is available for binding."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def get_default_ports(target_os: str) -> tuple[int, int]:
    """
    Return (nginx_port, backend_port) based on OS and privilege level.
    """
    is_windows = target_os.lower().startswith("win")
    
    # 1. Backend Port
    if is_windows:
        backend_port = int(os.environ.get("WAITRESS_PORT", 8066))
    else:
        backend_port = int(os.environ.get("GUNICORN_PORT", 8000))

    # 2. Frontend Nginx Port
    env_nginx_port = os.environ.get("NGINX_PORT")
    if env_nginx_port:
        nginx_port = int(env_nginx_port)
    else:
        # On Linux non-root, default to standard port 8080
        is_root = hasattr(os, "geteuid") and os.geteuid() == 0
        if is_root and is_port_free(80):
            nginx_port = 80
        else:
            nginx_port = 8080

    return nginx_port, backend_port


def generate_nginx_config(
    nginx_port: int,
    backend_port: int,
    target_os: str,
    upstream_servers: list[str] | None = None,
    lb_method: str = "least_conn"
) -> Path:
    """Generate and write the nginx-runtime.conf file."""
    is_windows = target_os.lower().startswith("win")

    # Ensure log and temp directories exist
    logs_dir = NGINX_DIR / "logs"
    temp_dir = NGINX_DIR / "temp"
    for sub in ["client_body", "proxy", "fastcgi", "uwsgi", "scgi"]:
        (temp_dir / sub).mkdir(parents=True, exist_ok=True)
    logs_dir.mkdir(parents=True, exist_ok=True)

    # Use forward slashes for Nginx paths regardless of OS
    root_str = str(PROJECT_ROOT).replace("\\", "/")
    nginx_dir_str = str(NGINX_DIR).replace("\\", "/")
    static_dir_str = f"{root_str}/src/static/"
    mime_types_str = f"{nginx_dir_str}/mime.types"

    # Upstream configuration
    if not upstream_servers:
        env_upstreams = os.environ.get("NGINX_UPSTREAM_SERVERS")
        if env_upstreams:
            upstream_servers = [s.strip() for s in env_upstreams.split(",") if s.strip()]
        else:
            upstream_servers = [f"127.0.0.1:{backend_port}"]

    # Validate load balancing method
    valid_methods = {"least_conn", "round_robin", "ip_hash"}
    method_directive = ""
    if lb_method == "least_conn":
        method_directive = "    least_conn;\n"
    elif lb_method == "ip_hash":
        method_directive = "    ip_hash;\n"
    elif lb_method != "round_robin":
        method_directive = "    least_conn;\n"

    upstream_lines = []
    for srv in upstream_servers:
        upstream_lines.append(f"    server {srv} max_fails=3 fail_timeout=10s;")
    upstreams_block = "\n".join(upstream_lines)

    # Windows-specific pid / directives
    pid_path = f"{logs_dir}/nginx.pid".replace("\\", "/")
    error_log_path = f"{logs_dir}/error.log".replace("\\", "/")
    access_log_path = f"{logs_dir}/access.log".replace("\\", "/")

    config_content = f"""# Auto-generated by setup_nginx.py for BioSecure AI
# Target OS: {target_os} | Frontend Port: {nginx_port} | Backend: {', '.join(upstream_servers)}

worker_processes auto;
error_log "{error_log_path}" warn;
pid "{pid_path}";

events {{
    worker_connections 1024;
}}

http {{
    include "{mime_types_str}";
    default_type application/octet-stream;

    # Real-time Telemetry & Performance Log Format
    log_format upstream_perf '$remote_addr - [$time_local] "$request" $status | '
                             'Backend: $upstream_addr | ResponseTime: ${{upstream_response_time}}s | TotalTime: ${{request_time}}s';
    access_log "{access_log_path}" upstream_perf;

    # Non-privileged temp paths (avoids permission errors in user-space)
    client_body_temp_path "{nginx_dir_str}/temp/client_body";
    proxy_temp_path       "{nginx_dir_str}/temp/proxy";
    fastcgi_temp_path     "{nginx_dir_str}/temp/fastcgi";
    uwsgi_temp_path       "{nginx_dir_str}/temp/uwsgi";
    scgi_temp_path        "{nginx_dir_str}/temp/scgi";

    # Performance
    sendfile on;
    tcp_nopush on;
    tcp_nodelay on;
    keepalive_timeout 65;
    types_hash_max_size 2048;

    # Gzip compression for static web assets
    gzip on;
    gzip_vary on;
    gzip_proxied any;
    gzip_comp_level 6;
    gzip_types text/plain text/css text/xml application/json application/javascript image/svg+xml;

    # High-resolution classroom group photos upload limit
    client_max_body_size 25M;

    # Upstream backend pool (Load balancing across workers/servers)
    upstream flask_app {{
{method_directive}{upstreams_block}
    }}

    server {{
        listen {nginx_port};
        server_name _;

        # Serve static assets directly from disk (zero Python overhead)
        location /static/ {{
            alias "{static_dir_str}";
            expires 7d;
            add_header Cache-Control "public, no-transform";
            add_header X-Handled-By "Nginx-Static-Engine" always;
            access_log off;
        }}

        # Progressive Web App (PWA) Service Worker & Manifest
        location = /sw.js {{
            proxy_pass http://flask_app/sw.js;
            add_header Cache-Control "no-cache";
            add_header Service-Worker-Allowed "/";
        }}

        location = /manifest.json {{
            proxy_pass http://flask_app/manifest.json;
            add_header Content-Type "application/manifest+json";
        }}

        # Load balancer & health monitor probe endpoint
        location /healthz {{
            proxy_pass http://flask_app/healthz;
            access_log off;
        }}

        # Live Real-Time Nginx Connection & Load Monitor Dashboard
        location /nginx_status {{
            stub_status;
            access_log off;
        }}

        # Proxy all attendance routes, viewer, and API requests to Python WSGI backend
        location / {{
            proxy_pass         http://flask_app;
            proxy_set_header   Host              $host;
            proxy_set_header   X-Real-IP         $remote_addr;
            proxy_set_header   X-Forwarded-For   $proxy_add_x_forwarded_for;
            proxy_set_header   X-Forwarded-Proto $scheme;

            # Telemetry Headers: Inspectable in Browser Developer Tools (F12)
            add_header X-Served-By "Nginx-Load-Balancer" always;
            add_header X-Load-Balancing-Technique "{lb_method}" always;
            add_header X-Backend-Server $upstream_addr always;
            add_header X-Backend-Response-Time $upstream_response_time always;

            # Extended timeouts for deep AI facial recognition inference
            proxy_connect_timeout 10s;
            proxy_send_timeout    300s;
            proxy_read_timeout    300s;

            # Client upload buffering to protect Python workers from slow uploads
            proxy_buffering on;
            proxy_buffer_size 128k;
            proxy_buffers 4 256k;
            proxy_busy_buffers_size 256k;
        }}
    }}
}}
"""
    output_path = NGINX_DIR / "nginx-runtime.conf"
    output_path.write_text(config_content, encoding="utf-8")
    return output_path


def main():
    parser = argparse.ArgumentParser(description="Configure Nginx for BioSecure AI.")
    parser.add_argument("--port", type=int, default=None, help="Nginx frontend listening port")
    parser.add_argument("--backend-port", type=int, default=None, help="Python backend port")
    parser.add_argument("--os", type=str, default=platform.system(), help="Target OS (Linux or Windows)")
    parser.add_argument("--lb", type=str, default="least_conn", choices=["least_conn", "round_robin", "ip_hash"], help="Load balancing algorithm")
    parser.add_argument("--upstreams", type=str, default=None, help="Comma-separated upstream servers (e.g. '127.0.0.1:8000,192.168.1.10:8000')")
    
    args = parser.parse_args()

    default_nginx_port, default_backend_port = get_default_ports(args.os)
    nginx_port = args.port or default_nginx_port
    backend_port = args.backend_port or default_backend_port

    upstreams = [s.strip() for s in args.upstreams.split(",")] if args.upstreams else None

    out_file = generate_nginx_config(
        nginx_port=nginx_port,
        backend_port=backend_port,
        target_os=args.os,
        upstream_servers=upstreams,
        lb_method=args.lb
    )

    print(f"NGINX_PORT={nginx_port}")
    print(f"BACKEND_PORT={backend_port}")
    print(f"CONFIG_FILE={out_file}")


if __name__ == "__main__":
    main()
